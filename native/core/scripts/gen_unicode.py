#!/usr/bin/env python3
"""Writes src/unicode_tables.h (extended grapheme cluster properties, Unicode 17) from the tables.rs of the Rust crate
unicode-segmentation, which Hugging Face tokenizers uses for the Precompiled normalizer:

    python3 scripts/gen_unicode.py ~/.cargo/registry/src/*/unicode-segmentation-1.13.3/src/tables.rs
"""
import pathlib
import re
import sys

src = pathlib.Path(sys.argv[1]).read_text()
version = re.search(r"pub const UNICODE_VERSION: \(u64, u64, u64\) = \((\d+), (\d+), (\d+)\);", src).groups()


def block(name):
    m = re.search(r"const " + name + r": &\[[^\]]*\] = &\[(.*?)\n\s*\];", src, re.S)
    return m.group(1)


cp = lambda s: int(s, 16)
cats = re.findall(r"\('\\u\{([0-9a-fA-F]+)\}',\s*'\\u\{([0-9a-fA-F]+)\}',\s*GC_(\w+)\)", block("grapheme_cat_table"))
incb_ext = re.findall(r"\('\\u\{([0-9a-fA-F]+)\}',\s*'\\u\{([0-9a-fA-F]+)\}'\)", block("InCB_Extend_table"))
linker = re.search(r"pub fn is_incb_linker\(c: char\) -> bool \{\s*matches!\(c,(.*?)\)\s*\}", src, re.S).group(1)
linkers = [cp(x) for x in re.findall(r"'\\u\{([0-9a-fA-F]+)\}'", linker)]
names = sorted({c for _, _, c in cats})
assert cats and incb_ext and linkers
# every entry of each table must have been read (entries may wrap across lines)
for name, got in (("grapheme_cat_table", cats), ("InCB_Extend_table", incb_ext)):
    assert block(name).count("('") == len(got), name
assert linker.count("'\\u{") == len(linkers)

out = [
    f"// Generated by scripts/gen_unicode.py from unicode-segmentation tables.rs (Unicode {'.'.join(version)}). Do not edit.",
    "// Grapheme_Cluster_Break with Extended_Pictographic and InCB=Consonant folded in (as in that crate).",
    "#ifndef PII_UNICODE_TABLES_H",
    "#define PII_UNICODE_TABLES_H",
    "#include <stdint.h>",
    "",
    "enum { GC_Any, " + ", ".join(f"GC_{n}" for n in names if n != "Any") + " };",
    "",
    "typedef struct { uint32_t lo, hi; uint8_t cat; } pii_gc_range;",
    f"static const pii_gc_range PII_GC_TABLE[{len(cats)}] = {{",
]
row = []
for lo, hi, c in cats:
    row.append(f"{{0x{cp(lo):x}, 0x{cp(hi):x}, GC_{c}}}")
    if len(row) == 6:
        out.append("  " + ", ".join(row) + ",")
        row = []
if row:
    out.append("  " + ", ".join(row) + ",")
out += ["};", "", f"static const uint32_t PII_INCB_EXTEND[{len(incb_ext)}][2] = {{"]
row = []
for lo, hi in incb_ext:
    row.append(f"{{0x{cp(lo):x}, 0x{cp(hi):x}}}")
    if len(row) == 8:
        out.append("  " + ", ".join(row) + ",")
        row = []
if row:
    out.append("  " + ", ".join(row) + ",")
out += ["};", "", f"static const uint32_t PII_INCB_LINKER[{len(linkers)}] = {{"]
out.append("  " + ", ".join(f"0x{x:x}" for x in linkers))
out += ["};", "", "#endif", ""]
dst = pathlib.Path(__file__).resolve().parent.parent / "src" / "unicode_tables.h"
dst.write_text("\n".join(out))
print(f"{dst}: {len(cats)} ranges, {len(incb_ext)} InCB=Extend ranges, {len(linkers)} linkers")
