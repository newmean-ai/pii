#!/usr/bin/env python3
"""Writes src/models.c (sizes and SHA-256 of the published model files) from the npm package's generated pins, so every
package checks downloads against the same values:

    python3 scripts/gen_models.py [../../js/src/models.ts]
"""
import json
import pathlib
import re
import sys

here = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else here.parent.parent / "js" / "src" / "models.ts"
ts = src.read_text()
version = re.search(r'MODEL_VERSION = "([^"]+)"', ts).group(1)
# the release tag in pii.h (download URLs) must name the same release as the pins
assert f'#define PII_MODEL_VERSION "{version}"' in (here / "pii.h").read_text(), f"set PII_MODEL_VERSION to {version} in pii.h"
files = json.loads(re.search(r"MODEL_FILES[^=]*= (\{.*\});", ts, re.S).group(1))
paths = {"q4": "onnx/model_q4.onnx", "q4e": "onnx/model_q4e.onnx", "tokenizer": "tokenizer.web.json"}

rows = []
for size in ("nano", "small", "medium", "large"):
    for f in ("q4", "q4e", "tokenizer"):
        info = files[size][f]
        assert re.fullmatch(r"[0-9a-f]{64}", info["sha256"])
        rows.append(f'  {{"{size}", "{f}", "{paths[f]}", {info["bytes"]}u, "{info["sha256"]}"}},')

out = f"""// Generated by scripts/gen_models.py from js/src/models.ts — do not edit by hand.
// Sizes and SHA-256 of the published model files (release {version}); downloads are checked against these before use.
#include <string.h>

#include "../pii.h"

static const pii_file_pin PINS[] = {{
{chr(10).join(rows)}
}};

const pii_file_pin *pii_model_file(const char *size, const char *file) {{
  if (!size || !file) return NULL;
  for (size_t i = 0; i < sizeof PINS / sizeof PINS[0]; i++)
    if (strcmp(PINS[i].size, size) == 0 && strcmp(PINS[i].file, file) == 0) return &PINS[i];
  return NULL;
}}
"""
(here / "src" / "models.c").write_text(out)
print(f"src/models.c: {len(rows)} files, release {version}")
