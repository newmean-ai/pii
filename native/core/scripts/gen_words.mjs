// Writes the word tables of the option whole_words (wholeWords) and of the block list's word boundaries, from one source:
//   native/core/src/word_tables.h   (C core)
//   js/src/word_tables.ts           (npm package; js/src/table.ts imports and re-exports it)
// The word-character predicate (Unicode L, N, M outside NO_SPACE), KO_PARTICLES and MAX_PARTICLE_RUN live here, so both
// packages read the same pinned Unicode 17.0 data whatever Unicode version their runtime has (since 1.4.0).
//   node scripts/gen_words.mjs        (needs a node whose Unicode data is 17.0: process.versions.unicode)
import { writeFileSync } from "node:fs";

const UNICODE = "17.0";
if (process.versions.unicode !== UNICODE) {
  console.error(`gen_words.mjs: node has Unicode ${process.versions.unicode}; the tables are pinned to Unicode ${UNICODE}`);
  process.exit(1);
}

/** Scripts written without spaces between words (Thai, Lao, Tibetan, Myanmar, Khmer, CJK, kana, Bopomofo, Yi): their letters
 *  never extend a span, since a "word" there would be a whole phrase. [lo, hi] pairs, sorted. */
const NO_SPACE = [
  0x0e00, 0x0eff, 0x0f00, 0x0fff, 0x1000, 0x109f, 0x1780, 0x17ff, 0x19e0, 0x19ff, 0x2e80, 0x2fdf, 0x3000, 0x312f, 0x3190, 0x31ff,
  0x3400, 0x4dbf, 0x4e00, 0x9fff, 0xa000, 0xa4cf, 0xa9e0, 0xa9ff, 0xaa60, 0xaa7f, 0xf900, 0xfaff, 0xff66, 0xff9f, 0x16fe0, 0x18cff,
  0x1aff0, 0x1b2ff, 0x20000, 0x3ffff,
];

/** Korean particles, copula endings and the honorifics 님 / 씨 / 들. A span that ends inside a Hangul word is not widened
 *  when the rest of the word is a run of these (「홍길동님께」 keeps 「님께」 = 님 + 께), since that rest is grammar, not part of
 *  the name; any other rest is widened (「남성」). At most 3 code points each. */
const KO_PARTICLES = [
  "님", "씨", "들", "께", "께서", "이", "가", "은", "는", "을", "를", "의", "에", "에서", "에게", "한테", "로", "으로", "와", "과",
  "랑", "하고", "도", "만", "까지", "부터", "처럼", "보다", "나", "든", "며", "야", "아", "이여", "이다", "입니다", "이고", "라고",
  "라", "인데", "니까", "이에요", "예요", "이요", "이죠", "였", "이었", "이었다", "였다", "이지", "지만", "면",
];
/** Longer rests are always widened. */
const MAX_PARTICLE_RUN = 12;

const LETTER = /[\p{L}\p{N}\p{M}]/u;
function isWordChar(c) {
  for (let i = 0; i < NO_SPACE.length; i += 2) {
    if (c < NO_SPACE[i]) break;
    if (c <= NO_SPACE[i + 1]) return false;
  }
  return LETTER.test(String.fromCodePoint(c));
}

const ranges = [];
let lo = -1;
for (let c = 0; c <= 0x110000; c++) {
  const w = c <= 0x10ffff && (c < 0xd800 || c > 0xdfff) && isWordChar(c);
  if (w && lo < 0) lo = c;
  if (!w && lo >= 0) ranges.push([lo, c - 1]), (lo = -1);
}
for (const p of KO_PARTICLES) if (Array.from(p).length > 3) throw new Error(`particle longer than 3 code points: ${p}`);

const hex = (x) => "0x" + x.toString(16);
const banner = `Generated by native/core/scripts/gen_words.mjs (Unicode ${UNICODE}). Do not edit.`;

// C: ranges as pairs, particles zero-padded to 3 code points
const particles = KO_PARTICLES.map((p) => {
  const cps = Array.from(p, (ch) => ch.codePointAt(0));
  return `{${[...cps, 0, 0, 0].slice(0, 3).map(hex).join(", ")}}, // ${p}`;
});
const rows = [];
for (let i = 0; i < ranges.length; i += 8) rows.push("  " + ranges.slice(i, i + 8).map(([a, b]) => `{${hex(a)}, ${hex(b)}}`).join(", ") + ",");
writeFileSync(
  new URL("../src/word_tables.h", import.meta.url),
  `// ${banner}\n` +
    `// Word characters of the option whole_words and of block-list boundaries: Unicode L, N, M outside the scripts written\n` +
    `// without spaces. Same data as js/src/word_tables.ts.\n` +
    `#ifndef PII_WORD_TABLES_H\n#define PII_WORD_TABLES_H\n#include <stdint.h>\n\n` +
    `static const uint32_t PII_WORD_TABLE[${ranges.length}][2] = {\n${rows.join("\n")}\n};\n\n` +
    `// KO_PARTICLES (zero-padded) and MAX_PARTICLE_RUN: a Hangul word end is not widened over a run of these.\n` +
    `#define PII_MAX_PARTICLE_RUN ${MAX_PARTICLE_RUN}\n` +
    `static const uint32_t PII_KO_PARTICLES[${particles.length}][3] = {\n${particles.map((p) => "  " + p).join("\n")}\n};\n\n#endif\n`,
);

// TypeScript: ranges flattened and delta-coded (lo0, hi0 - lo0, lo1 - hi0, ...) to keep the bundle small
const flat = ranges.flat();
const deltas = flat.map((x, i) => (i ? x - flat[i - 1] : x));
const lines = [];
for (let i = 0; i < deltas.length; i += 32) lines.push("  " + deltas.slice(i, i + 32).join(",") + ",");
const wrap = (xs, per) => {
  const out = [];
  for (let i = 0; i < xs.length; i += per) out.push("  " + xs.slice(i, i + per).join(", ") + ",");
  return out.join("\n");
};
writeFileSync(
  new URL("../../../js/src/word_tables.ts", import.meta.url),
  `// ${banner}\n` +
    `// Same data as native/core/src/word_tables.h, so wholeWords and block-list boundaries do not depend on the runtime's\n` +
    `// Unicode version.\n\n` +
    `/** Scripts written without spaces between words (Thai, Lao, Tibetan, Myanmar, Khmer, CJK, kana, Bopomofo, Yi): their letters\n` +
    ` *  never extend a span, since a "word" there would be a whole phrase. [lo, hi] pairs, sorted. */\n` +
    `export const NO_SPACE: readonly number[] = [\n${wrap(NO_SPACE.map(hex), 16)}\n];\n\n` +
    `const DELTAS = [\n${lines.join("\n")}\n];\n` +
    `/** Word characters (Unicode ${UNICODE} L, N, M outside NO_SPACE): sorted, disjoint [lo, hi] ranges, flattened. */\n` +
    `export const WORD_RANGES: Uint32Array = (() => {\n` +
    `  const r = new Uint32Array(DELTAS.length);\n` +
    `  for (let i = 0, x = 0; i < DELTAS.length; i++) r[i] = x += DELTAS[i];\n` +
    `  return r;\n` +
    `})();\n\n` +
    `/** Korean particles, copula endings and the honorifics 님 / 씨 / 들. A span that ends inside a Hangul word is not widened\n` +
    ` *  when the rest of the word is a run of these (「홍길동님께」 keeps 「님께」 = 님 + 께), since that rest is grammar, not part of\n` +
    ` *  the name; any other rest is widened (「남성」). At most 3 code points each. */\n` +
    `export const KO_PARTICLES: readonly string[] = [\n${wrap(KO_PARTICLES.map((p) => JSON.stringify(p)), 20)}\n];\n` +
    `/** Longer rests are always widened. */\n` +
    `export const MAX_PARTICLE_RUN = ${MAX_PARTICLE_RUN};\n`,
);
console.log(`${ranges.length} ranges, ${KO_PARTICLES.length} particles, Unicode ${UNICODE}`);
