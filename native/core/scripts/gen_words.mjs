// Writes src/word_tables.h: the code points that isWordChar of js/src/table.ts accepts (Unicode L, N, M of this node's
// Unicode version, minus NO_SPACE), as sorted ranges, and KO_PARTICLES as code points, so the C core widens to whole words
// exactly as the npm package does.
//   node scripts/gen_words.mjs        (node 23.6+ reads the TypeScript file directly)
import { writeFileSync } from "node:fs";
import { isWordChar, KO_PARTICLES, MAX_PARTICLE_RUN } from "../../../js/src/table.ts";

const ranges = [];
let lo = -1;
for (let c = 0; c <= 0x110000; c++) {
  const w = c <= 0x10ffff && (c < 0xd800 || c > 0xdfff) && isWordChar(c);
  if (w && lo < 0) lo = c;
  if (!w && lo >= 0) ranges.push([lo, c - 1]), (lo = -1);
}
const hex = (x) => "0x" + x.toString(16);
const particles = KO_PARTICLES.map((p) => {
  const cps = Array.from(p, (ch) => ch.codePointAt(0));
  if (cps.length > 3) throw new Error(`particle longer than 3 code points: ${p}`);
  return `{${[...cps, 0, 0, 0].slice(0, 3).map(hex).join(", ")}}, // ${p}`;
});
const rows = [];
for (let i = 0; i < ranges.length; i += 8) rows.push("  " + ranges.slice(i, i + 8).map(([a, b]) => `{${hex(a)}, ${hex(b)}}`).join(", ") + ",");
writeFileSync(
  new URL("../src/word_tables.h", import.meta.url),
  `// Generated by scripts/gen_words.mjs from js/src/table.ts (Unicode ${process.versions.unicode}). Do not edit.\n` +
    `// Word characters of the option whole_words: Unicode L, N, M outside the scripts written without spaces.\n` +
    `#ifndef PII_WORD_TABLES_H\n#define PII_WORD_TABLES_H\n#include <stdint.h>\n\n` +
    `static const uint32_t PII_WORD_TABLE[${ranges.length}][2] = {\n${rows.join("\n")}\n};\n\n` +
    `// KO_PARTICLES (zero-padded) and MAX_PARTICLE_RUN: a Hangul word end is not widened over a run of these.\n` +
    `#define PII_MAX_PARTICLE_RUN ${MAX_PARTICLE_RUN}\n` +
    `static const uint32_t PII_KO_PARTICLES[${particles.length}][3] = {\n${particles.map((p) => "  " + p).join("\n")}\n};\n\n#endif\n`,
);
console.log(`${ranges.length} ranges, ${particles.length} particles, Unicode ${process.versions.unicode}`);
