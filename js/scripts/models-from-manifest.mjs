// Writes src/models.ts from the manifest.json produced by training/scripts/export_web.py:
//   node scripts/models-from-manifest.mjs <path/to/manifest.json>
import { readFileSync, writeFileSync } from "node:fs";

const m = JSON.parse(readFileSync(process.argv[2], "utf8"));
const pick = (f) => ({ bytes: f.bytes, sha256: f.sha256 });
const tiers = Object.fromEntries(
  Object.entries(m.tiers).map(([t, f]) => [
    t,
    { q4: pick(f["onnx/model_q4.onnx"]), q4e: pick(f["onnx/model_q4e.onnx"]), tokenizer: pick(f["tokenizer.web.json"]) },
  ]),
);
writeFileSync(
  new URL("../src/models.ts", import.meta.url),
  `// Generated by scripts/models-from-manifest.mjs — do not edit by hand.
// Sizes and SHA-256 of the published model files; downloads are checked against these before use.

export const MODEL_VERSION = ${JSON.stringify(m.version)};

export type Size = "nano" | "small" | "medium" | "large";
export type Variant = "q4" | "q4e";

export interface FileInfo {
  bytes: number;
  sha256: string;
}

export const MODEL_FILES: Record<Size, { q4: FileInfo; q4e: FileInfo; tokenizer: FileInfo }> = ${JSON.stringify(tiers, null, 2)};
`,
);
