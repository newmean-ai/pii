// engine/build/pii.wasm and pii-relaxed.wasm → src/engines/wasm-simd.ts and wasm-relaxed.ts (base64), so the package needs no
// .wasm loader in the app's bundler. Each is its own chunk; a browser loads only the build it runs. Run after engine/build.sh.
import { readFileSync, writeFileSync } from "node:fs";

for (const [wasm, ts] of [["pii.wasm", "wasm-simd.ts"], ["pii-relaxed.wasm", "wasm-relaxed.ts"]]) {
  const b64 = readFileSync(new URL(`../engine/build/${wasm}`, import.meta.url)).toString("base64");
  writeFileSync(
    new URL(`../src/engines/${ts}`, import.meta.url),
    `// Generated by scripts/embed-wasm.mjs from engine/build/${wasm} — do not edit by hand.\nexport const WASM: string = "${b64}";\n`,
  );
}
