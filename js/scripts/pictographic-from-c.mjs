// Writes src/pictographic.ts: the Extended_Pictographic ranges of the C core's Unicode table
// (native/core/src/unicode_tables.h), so the npm package classifies emoji exactly as the C core does whatever Unicode
// version the JavaScript engine has.   node scripts/pictographic-from-c.mjs
import { readFileSync, writeFileSync } from "node:fs";

const h = readFileSync(new URL("../../native/core/src/unicode_tables.h", import.meta.url), "utf8");
const version = /Unicode (\d+\.\d+\.\d+)/.exec(h)[1];
const ranges = [...h.matchAll(/\{0x([0-9a-f]+), 0x([0-9a-f]+), GC_Extended_Pictographic\}/g)].map((m) => [parseInt(m[1], 16), parseInt(m[2], 16)]);
const body = ranges.map(([a, b]) => `${a},${b}`).join(",");
writeFileSync(
  new URL("../src/pictographic.ts", import.meta.url),
  `// Generated by scripts/pictographic-from-c.mjs from native/core/src/unicode_tables.h (Unicode ${version}). Do not edit.\n` +
    `// Extended_Pictographic as [lo, hi] pairs, sorted.\nexport const PICTOGRAPHIC: readonly number[] = [${body}];\n`,
);
console.log(`${ranges.length} ranges, Unicode ${version}`);
