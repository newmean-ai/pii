#!/usr/bin/env python3
"""Writes lib/src/upper.dart: the Unicode uppercase mapping (UnicodeData.txt and the unconditional mappings of
SpecialCasing.txt, where one letter becomes two or three: a sharp s as "SS", the ligature fi as "FI", ...), which the
vault uses to find a value written in capitals. Dart's String.toUpperCase maps one character to one, from older Unicode
data, while the other packages' runtimes apply the full mapping (JavaScript toUpperCase, Python str.upper, Rust
to_uppercase, Swift, Kotlin). Run with the Python whose Unicode version should be pinned: python3 tool/gen_upper.py
"""
import sys
import unicodedata
from pathlib import Path

runs, special = [], []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    up = chr(cp).upper()
    if up == chr(cp):
        continue
    if len(up) > 1:
        special.append((cp, [ord(c) for c in up]))
        continue
    delta = ord(up) - cp
    if runs:
        first, last, stride, d = runs[-1]
        if d == delta and ((first == last and cp - last in (1, 2)) or (first != last and cp - last == stride)):
            runs[-1] = (first, cp, cp - last, d)
            continue
    runs.append((cp, cp, 1, delta))

lines = [
    f"// Generated by tool/gen_upper.py (Unicode {unicodedata.unidata_version}): the uppercase mapping of every letter whose",
    "// capitals differ from it. Do not edit.",
    "",
    "/// Runs of letters that map one to one: first, last, stride (every stride-th code point from first to last), and the",
    "/// difference to add to each of them.",
    "const List<int> upperRuns = [",
]
for first, last, stride, delta in runs:
    lines.append(f"  0x{first:X}, 0x{last:X}, {stride}, {delta}, //")
lines += [
    "];",
    "",
    "/// The letters whose capitals are more than one character (SpecialCasing.txt, the mappings that hold in every",
    "/// language), and those capitals.",
    "const Map<int, List<int>> specialUpper = {",
]
for cp, up in special:
    lines.append(f"  0x{cp:X}: [{', '.join(f'0x{c:X}' for c in up)}],")
lines.append("};")
Path(__file__).resolve().parent.parent.joinpath("lib", "src", "upper.dart").write_text("\n".join(lines) + "\n")
print(f"{len(runs)} runs, {len(special)} special, Unicode {unicodedata.unidata_version}", file=sys.stderr)
