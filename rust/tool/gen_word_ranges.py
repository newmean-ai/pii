#!/usr/bin/env python3
"""Writes src/word_ranges.rs: the code point ranges of Unicode general categories L, N and M (letters, numbers, marks),
the word characters of the vault's edge rule in every newmean-pii package, and of category M alone (marks), which join
the character before them into one grapheme cluster (the others ask their runtime; Rust's standard library has no
general category). Run with the Python whose Unicode version should be pinned: python3 tool/gen_word_ranges.py
"""
import sys
import unicodedata
from pathlib import Path


def ranges_of(test):
    out, start = [], None
    for cp in range(0x110000):
        hit = test(unicodedata.category(chr(cp)))
        if hit and start is None:
            start = cp
        if not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, ranges):
    lines = [f"pub(crate) const {name}: [(u32, u32); {len(ranges)}] = ["]
    row = []
    for a, b in ranges:
        row.append(f"(0x{a:X}, 0x{b:X})")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("];")
    return lines


words = ranges_of(lambda cat: cat[0] in "LNM")
marks = ranges_of(lambda cat: cat[0] == "M")
lines = [
    f"// Generated by tool/gen_word_ranges.py (Unicode {unicodedata.unidata_version}): general categories L, N and M. Do not edit.",
    *table("WORD_RANGES", words),
    "",
    "// General category M (marks).",
    *table("MARK_RANGES", marks),
]
Path(__file__).resolve().parent.parent.joinpath("src", "word_ranges.rs").write_text("\n".join(lines) + "\n")
print(f"{len(words)} word ranges, {len(marks)} mark ranges, Unicode {unicodedata.unidata_version}", file=sys.stderr)
